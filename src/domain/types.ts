/**
 * Canonical domain model (docs/ARCHITECTURE.md, Revision 2 §2–3; ADR-004).
 * Renderer-independent: nothing in src/domain may import React, React Flow, or Three.js.
 */

export type EntityId = string;

export const PROVIDERS = ['aws', 'azure', 'gcp', 'on-prem', 'saas', 'internal', 'unknown'] as const;
export type Provider = (typeof PROVIDERS)[number];

export const HEALTH_STATUSES = ['healthy', 'degraded', 'unavailable', 'unknown'] as const;
export type HealthStatus = (typeof HEALTH_STATUSES)[number];

export const ENVIRONMENT_KINDS = ['development', 'staging', 'production', 'other'] as const;
export type EnvironmentKind = (typeof ENVIRONMENT_KINDS)[number];

export const SERVICE_CATEGORIES = [
  'api',
  'gateway',
  'application',
  'worker',
  'scheduled-job',
  'other',
] as const;
export type ServiceCategory = (typeof SERVICE_CATEGORIES)[number];

export const RESOURCE_TYPES = [
  // Containment levels
  'account',
  'subscription',
  'project',
  'region',
  'datacenter',
  'cluster',
  'namespace',
  'workload',
  // Backing resources that can take part in communication
  'database',
  'cache',
  'search-index',
  'broker',
  'topic',
  'queue',
  'exchange',
  'external-resource',
  'other',
] as const;
export type ResourceType = (typeof RESOURCE_TYPES)[number];

/** Resource types that only express containment ("where does this run?") and never communicate. */
export const CONTAINMENT_ONLY_RESOURCE_TYPES: ReadonlySet<ResourceType> = new Set<ResourceType>([
  'account',
  'subscription',
  'project',
  'region',
  'datacenter',
  'cluster',
  'namespace',
]);

export const PROTOCOLS = [
  'http',
  'https',
  'graphql',
  'grpc',
  'websocket',
  'kafka',
  'rabbitmq',
  'tcp',
  'tls',
  'postgresql',
  'mysql',
  'mongodb',
  'redis',
  'other',
] as const;
export type Protocol = (typeof PROTOCOLS)[number];

export const COMMUNICATION_PATTERNS = [
  'synchronous',
  'asynchronous',
  'streaming',
  'scheduled',
  'database',
  'unknown',
] as const;
export type CommunicationPattern = (typeof COMMUNICATION_PATTERNS)[number];

export type RelationshipDirection = 'unidirectional' | 'bidirectional';

export const RELATIONSHIP_STATUSES = ['active', 'degraded', 'inactive', 'unknown'] as const;
export type RelationshipStatus = (typeof RELATIONSHIP_STATUSES)[number];

/** Telemetry. `isSimulated` must be true for anything generated by mocks or simulation. */
export interface Metrics {
  latencyMs?: number;
  throughputPerSecond?: number;
  errorRatePercent?: number;
  isSimulated: boolean;
  observedAt?: string;
}

export interface EnvironmentRecord {
  id: EntityId;
  name: string;
  kind: EnvironmentKind;
}

/** A logical capability. Has no environment; it is deployed as one or more instances. */
export interface ServiceDefinition {
  id: EntityId;
  name: string;
  description?: string;
  owner?: string;
  team?: string;
  category: ServiceCategory;
  protocols: Protocol[];
  metadata?: Record<string, unknown>;
}

/** One deployment of a ServiceDefinition in exactly one environment. */
export interface ServiceInstance {
  id: EntityId;
  serviceDefinitionId: EntityId;
  environmentId: EntityId;
  provider: Provider;
  health: HealthStatus;
  version?: string;
  endpoint?: string;
  /** The resource the instance runs in (workload, namespace, …), where known. */
  resourceId?: EntityId;
  metrics?: Metrics;
  updatedAt: string;
  metadata?: Record<string, unknown>;
}

/** Infrastructure, containment levels, and first-class messaging resources (topics, queues, exchanges). */
export interface InfrastructureResource {
  id: EntityId;
  name: string;
  type: ResourceType;
  provider: Provider;
  parentResourceId?: EntityId;
  environmentId?: EntityId;
  /** Optional; see ADR-008. Absent means health is not modeled for this resource. */
  health?: HealthStatus;
  owner?: string;
  team?: string;
  metrics?: Metrics;
  updatedAt?: string;
  metadata?: Record<string, unknown>;
}

/** Runtime communication ("what talks to what?"). Never used for containment. */
export interface CommunicationRelationship {
  id: EntityId;
  /** A ServiceInstance or a non-containment InfrastructureResource. */
  sourceEntityId: EntityId;
  targetEntityId: EntityId;
  protocol: Protocol;
  pattern: CommunicationPattern;
  direction: RelationshipDirection;
  status: RelationshipStatus;
  authenticationType?: string;
  endpoint?: string;
  metrics?: Metrics;
  metadata?: Record<string, unknown>;
  updatedAt: string;
}

/** Resource types that can carry event types (ADR-014). */
export const EVENT_CHANNEL_TYPES: ReadonlySet<ResourceType> = new Set<ResourceType>(['topic', 'queue', 'exchange']);

/**
 * A logical message contract (e.g. `OrderPlaced`), environment-independent like a ServiceDefinition
 * (ADR-014). It annotates existing communication and never creates any: in each environment it
 * resolves to the channel there and to the producer/consumer instances' relationships with it.
 */
export interface EventType {
  id: EntityId;
  name: string;
  description?: string;
  schemaVersion?: string;
  owner?: string;
  team?: string;
  /** Topic, queue, or exchange resources carrying the event; at most one per environment. */
  channelResourceIds: EntityId[];
  /** Service definitions that publish the event. */
  producerServiceIds: EntityId[];
  /** Service definitions that consume the event. */
  consumerServiceIds: EntityId[];
  metadata?: Record<string, unknown>;
}

/** Everything a repository returns. Plain serializable data. */
export interface TopologyData {
  environments: EnvironmentRecord[];
  serviceDefinitions: ServiceDefinition[];
  serviceInstances: ServiceInstance[];
  resources: InfrastructureResource[];
  relationships: CommunicationRelationship[];
  /** Optional (additive within v1, ADR-014). Absent means no event catalog is modeled. */
  eventTypes?: EventType[];
}

export const ENTITY_KINDS = [
  'environment',
  'service-definition',
  'service-instance',
  'resource',
  'relationship',
] as const;
export type EntityKind = (typeof ENTITY_KINDS)[number];

/** How every view refers to an entity: canonical kind + ID (ARCHITECTURE §7). */
export interface EntityRef {
  kind: EntityKind;
  id: EntityId;
}
